function Outputs = CreateFixedWeightBatteryTechnologyVariants(SourceFile, OutputDirectory)
%CREATEFIXEDWEIGHTBATTERYTECHNOLOGYVARIANTS Increase energy at fixed HEA mass.
%
% The source 250 Wh/kg sized HEA is preserved exactly except for battery
% specific energy and equivalent cell capacity. Battery mass, cell count,
% voltage, aircraft weights, propulsion hardware, and geometry are fixed.

if nargin < 1 || strlength(string(SourceFile)) == 0
    SourceFile = fullfile(fileparts(mfilename("fullpath")), ...
        "ERJ175LR_current_Lam_10pctTko_30pctEMClimb.mat");
end
if nargin < 2 || strlength(string(OutputDirectory)) == 0
    OutputDirectory = fileparts(mfilename("fullpath"));
end
SourceFile = char(string(SourceFile));
OutputDirectory = char(string(OutputDirectory));
if ~isfile(SourceFile)
    error("FAST:FixedWeightBattery:MissingSource", ...
        "Original 250 Wh/kg sized HEA does not exist: %s", SourceFile);
end
if ~isfolder(OutputDirectory), mkdir(OutputDirectory); end

Source = load(SourceFile, "SizedAircraft");
if ~isfield(Source, "SizedAircraft")
    error("FAST:FixedWeightBattery:BadSource", ...
        "Source file must contain SizedAircraft.");
end
OriginalPHE = Source.SizedAircraft;
if string(OriginalPHE.Specs.Propulsion.PropArch.Type) ~= "PHE"
    error("FAST:FixedWeightBattery:WrongArchitecture", ...
        "Source aircraft must use the PHE architecture.");
end

BaselineSpecificEnergy_Whkg = ...
    OriginalPHE.Specs.Power.SpecEnergy.Batt / 3.6e3;
if abs(BaselineSpecificEnergy_Whkg - 250) > 1e-8
    error("FAST:FixedWeightBattery:WrongBaseline", ...
        "Expected a 250 Wh/kg source HEA; found %.12g Wh/kg.", ...
        BaselineSpecificEnergy_Whkg);
end
OriginalWeights = OriginalPHE.Specs.Weight;
OriginalCellCapacity_Ah = OriginalPHE.Specs.Battery.CapCell;

% Build one conventional reference with the same calibration factors as
% the preserved source HEA. This does not alter the HEA variants.
ConventionalDefinition = AircraftSpecsPkg.ERJ175LR();
ConventionalDefinition.Specs.Propulsion.MDotCF = ...
    OriginalPHE.Specs.Propulsion.MDotCF;
ConventionalDefinition.Specs.Weight.WairfCF = ...
    OriginalPHE.Specs.Weight.WairfCF;
BaseConventional = Main(ConventionalDefinition, ...
    @MissionProfilesPkg.ERJ_ClimbThenAccel);
if ~logical(BaseConventional.Settings.Converged)
    error("FAST:FixedWeightBattery:ConventionalSizing", ...
        "The calibration-matched conventional reference did not converge.");
end

Technologies = [500; 1000];
Files = strings(numel(Technologies), 1);
Rows = cell(numel(Technologies), 1);
for k = 1:numel(Technologies)
    Technology = Technologies(k);
    Scale = Technology / BaselineSpecificEnergy_Whkg;
    BasePHE = OriginalPHE;
    BasePHE.Specs.Power.SpecEnergy.Batt = Technology * 3.6e3;
    BasePHE.Specs.Battery.CapCell = OriginalCellCapacity_Ah * Scale;

    if ~isequaln(BasePHE.Specs.Weight, OriginalWeights)
        error("FAST:FixedWeightBattery:WeightChanged", ...
            "Aircraft weights changed while creating the %g Wh/kg case.", ...
            Technology);
    end

    MassBasedEnergy_kWh = BasePHE.Specs.Weight.Batt * ...
        BasePHE.Specs.Power.SpecEnergy.Batt / 3.6e6;
    CellModelEnergy_kWh = BasePHE.Specs.Battery.NomVolCell * ...
        BasePHE.Specs.Battery.CapCell * ...
        BasePHE.Specs.Power.Battery.ParCells * ...
        BasePHE.Specs.Power.Battery.SerCells / 1000;
    if abs(MassBasedEnergy_kWh - CellModelEnergy_kWh) > ...
            1e-8 * max(1, MassBasedEnergy_kWh)
        error("FAST:FixedWeightBattery:EnergyMismatch", ...
            "Mass- and cell-based battery energies do not agree.");
    end

    SizingMetadata = struct( ...
        "Study", "fixed original 250 Wh/kg HEA weight; increased battery energy", ...
        "SourceAircraftFile", string(SourceFile), ...
        "BaselineBatterySpecificEnergy_Whkg", BaselineSpecificEnergy_Whkg, ...
        "BatterySpecificEnergy_Whkg", Technology, ...
        "ActualBatterySpecificEnergy_Whkg", ...
            BasePHE.Specs.Power.SpecEnergy.Batt / 3.6e3, ...
        "BatteryEnergyScale", Scale, ...
        "PHE_MTOW_kg", BasePHE.Specs.Weight.MTOW, ...
        "PHE_OEW_kg", BasePHE.Specs.Weight.OEW, ...
        "PHE_BatteryWeight_kg", BasePHE.Specs.Weight.Batt, ...
        "PHE_BatteryEnergy_kWh", MassBasedEnergy_kWh, ...
        "PHE_CellModelEnergy_kWh", CellModelEnergy_kWh, ...
        "PHE_CellCapacity_Ah", BasePHE.Specs.Battery.CapCell, ...
        "PHE_DesignFuel_kg", BasePHE.Specs.Weight.Fuel, ...
        "PHE_ElectricMachineWeight_kg", BasePHE.Specs.Weight.EM, ...
        "PHEConverged", logical(BasePHE.Settings.Converged), ...
        "ConventionalConverged", logical(BaseConventional.Settings.Converged), ...
        "Generated", string(datetime("now")));

    OutputFile = fullfile(OutputDirectory, sprintf( ...
        "ERJ175LR_PHE_Fixed250Weight_%dWhkg.mat", Technology));
    save(OutputFile, "BasePHE", "BaseConventional", ...
        "SizingMetadata", "-v7.3");
    Files(k) = string(OutputFile);
    Rows{k} = struct2table(SizingMetadata, "AsArray", true);
end

Summary = vertcat(Rows{:});
writetable(Summary, fullfile(OutputDirectory, ...
    "ERJ175LR_PHE_Fixed250Weight_BatteryVariants.csv"));
Outputs = table(Technologies, Files, ...
    'VariableNames', {'BatterySpecificEnergy_Whkg','File'});
disp(Summary(:, ["BatterySpecificEnergy_Whkg","PHE_BatteryWeight_kg", ...
    "PHE_BatteryEnergy_kWh","PHE_MTOW_kg","PHE_OEW_kg", ...
    "PHE_DesignFuel_kg"]));
end
