function CacheFile = ImportFixedBaselineCheckpointForReuse( ...
        CheckpointFile, PreparedBaseFile, CacheDirectory)
%IMPORTFIXEDBASELINECHECKPOINTFORREUSE Seed a reusable cache from a full run.

if nargin < 1 || strlength(string(CheckpointFile)) == 0
    CheckpointFile = fullfile(pwd, "output", ...
        "local_rep100_sequence8_v6", "tasks", "Sequence_0008", ...
        "checkpoints", "Sequence_0008.mat");
end
if nargin < 2 || strlength(string(PreparedBaseFile)) == 0
    PreparedBaseFile = fullfile(pwd, "output", ...
        "local_rep100_sequence8_v6", "prepared", ...
        "SelectedHEA_BaseAircraft.mat");
end
if nargin < 3 || strlength(string(CacheDirectory)) == 0
    CacheDirectory = fullfile(pwd, "output", ...
        "local_rep100_precomputed_v6", "fixed_baseline_cache");
end
if ~isfile(CheckpointFile)
    error("FAST:MissingCheckpoint", "Checkpoint does not exist: %s", ...
        CheckpointFile);
end
if ~isfile(PreparedBaseFile)
    error("FAST:MissingPreparedAircraft", ...
        "Prepared aircraft does not exist: %s", PreparedBaseFile);
end
if ~isfolder(CacheDirectory), mkdir(CacheDirectory); end

D = load(CheckpointFile, "Status", "RunMetadata", "Sequence", ...
    "MissionResults", "ChargeHistories", "OptimizerResults");
P = load(PreparedBaseFile, "BasePHE");
P.BasePHE.Specs.Battery.Charging = 150e3;
P.BasePHE.Settings.BatterySOH_pct = 80;
P.BasePHE.Settings.BatteryInitialTemperature_C = 35;
if string(D.Status) ~= "success"
    error("FAST:IncompleteCheckpoint", ...
        "Only a successful sequence checkpoint can seed the baseline cache.");
end

Sequence = D.Sequence;
UnoptimizedMissionResults = D.MissionResults.Unoptimized;
UnoptimizedCharge = D.ChargeHistories.Unoptimized;
UnoptimizedPC = D.OptimizerResults.UnoptimizedPC;
UnoptimizedReplayOutput = ...
    D.OptimizerResults.UnoptimizedReplayOutput;
FixedClimbMotorPower_kW = ...
    D.OptimizerResults.FixedClimbMotorPower_kW;
FixedClimbMotorPower_pct = ...
    D.OptimizerResults.FixedClimbMotorPower_pct;
FixedBaselineMetadata = struct( ...
    "Status", "success", ...
    "RunVersion", string(D.RunMetadata.RunVersion), ...
    "SequenceIndex", D.RunMetadata.SequenceIndex, ...
    "Flights", height(Sequence), ...
    "AircraftFingerprint", AircraftFingerprint(P.BasePHE), ...
    "Completed", string(datetime("now")));

CacheFile = fullfile(CacheDirectory, sprintf( ...
    "Sequence_%04d_fixed_baseline.mat", ...
    FixedBaselineMetadata.SequenceIndex));
save(CacheFile, "FixedBaselineMetadata", "Sequence", ...
    "UnoptimizedMissionResults", "UnoptimizedCharge", ...
    "UnoptimizedPC", "UnoptimizedReplayOutput", ...
    "FixedClimbMotorPower_kW", "FixedClimbMotorPower_pct", "-v7.3");
fprintf("Imported fixed baseline cache: %s\n", CacheFile);
end


function Fingerprint = AircraftFingerprint(Aircraft)
Fingerprint = struct( ...
    "MTOW_kg", Aircraft.Specs.Weight.MTOW, ...
    "Fuel_kg", Aircraft.Specs.Weight.Fuel, ...
    "MotorSLSPower_W", Aircraft.Specs.Propulsion.SLSPower( ...
        Aircraft.Specs.Propulsion.PropArch.TrnType == 0), ...
    "BatterySpecificEnergy_Jpkg", Aircraft.Specs.Power.SpecEnergy.Batt, ...
    "ClimbLiftToDragCF", Aircraft.Specs.Aero.L_D.ClbCF, ...
    "CruiseLiftToDragCF", Aircraft.Specs.Aero.L_D.CrsCF, ...
    "FuelFlowCF", Aircraft.Specs.Propulsion.MDotCF, ...
    "AirframeWeightCF", Aircraft.Specs.Weight.WairfCF, ...
    "ChargerPower_W", Aircraft.Specs.Battery.Charging, ...
    "BatterySOH_pct", Aircraft.Settings.BatterySOH_pct, ...
    "BatteryInitialTemperature_C", ...
        Aircraft.Settings.BatteryInitialTemperature_C);
end
