function SmokeResult = RunGreatLakesSmokeTest()
%RUNGREATLAKESSMOKETEST Short end-to-end joint-optimizer preflight.
%
% Sizes both ERJ175LR aircraft from the checked-out source, then exercises
% the complete sequence-50 joint-optimizer initialization and fixed-command
% replay without spending time on fmincon iterations.  Any infeasible replay
% or configuration failure makes the Slurm job fail.

SmokeVersion = "all-sequences-v4-source-sized-base-aircraft";
ResultsRoot = RequireEnvironmentPath("FAST_GL_RESULTS_DIR");
SmokeDir = fullfile(ResultsRoot, "smoke");
if ~isfolder(SmokeDir), mkdir(SmokeDir); end
MarkerFile = fullfile(SmokeDir, "SmokeTest.passed");
if isfile(MarkerFile), delete(MarkerFile); end

[PHE, Conventional, SizingMetadata] = SizeERJ175LRBaseAircraft();
SequenceData = load(fullfile(fileparts(mfilename("fullpath")), ...
    "Sequence.mat"), "tables");
SequenceIndex = 50;
Sequence = SequenceData.tables{SequenceIndex};

PHE.Settings.PowerOptMaxIter = 0;
PHE.Settings.PowerOptMaxStarts = 1;
PHE.Settings.PowerOptUseParallel = false;
PHE.Settings.PrintOut = 0;
PHE.Settings.Plotting = 0;
PHE.Settings.Table = 0;
PHE.Specs.Battery.Charging = 150e3;
PHE.Settings.GroundChargeModel = "ThermalEquivalentCircuit";
PHE.Settings.BatterySOH_pct = 80;
PHE.Settings.BatteryInitialTemperature_C = 35;

[AircraftByFlight, PC, OptimizerTime_min, OptSeqTable, ExitFlag, ...
    OptimizerOutput] = OptimizationPkg.SequencePowerOpt(PHE, Sequence);

if ExitFlag ~= 0 || OptimizerOutput.iterations ~= 0 || ...
        ~isfield(OptimizerOutput, "Feasible") || ...
        ~logical(OptimizerOutput.Feasible) || ...
        ~isfield(OptimizerOutput, "MaxConstraint") || ...
        OptimizerOutput.MaxConstraint > 5e-5
    error("GreatLakes:SmokeTestFailed", ...
        "Sequence 50 did not produce a feasible zero-iteration replay.");
end

nFlight = height(Sequence);
Fuel_kg = zeros(nFlight, 1);
InitialSOC_pct = zeros(nFlight, 1);
FinalSOC_pct = zeros(nFlight, 1);
for iFlight = 1:nFlight
    Aircraft = AircraftByFlight.(sprintf("Aircraft%d", iFlight));
    MainSegments = find(Aircraft.Mission.Profile.ID == 1);
    MainEnd = Aircraft.Mission.Profile.SegEnd(MainSegments(end));
    Battery = find(Aircraft.Specs.Propulsion.PropArch.SrcType == 0, 1);
    Fuel_kg(iFlight) = Aircraft.Mission.History.SI.Weight.Fburn(MainEnd);
    InitialSOC_pct(iFlight) = ...
        Aircraft.Mission.History.SI.Power.SOC(1, Battery);
    FinalSOC_pct(iFlight) = ...
        Aircraft.Mission.History.SI.Power.SOC(MainEnd, Battery);
end

FlightSummary = table((1:nFlight)', Sequence.DISTANCE, Fuel_kg, ...
    InitialSOC_pct, FinalSOC_pct, ...
    'VariableNames', {'Flight','Distance_nmi','MainMissionFuel_kg', ...
    'InitialSOC_pct','FinalSOC_pct'});
SmokeResult = struct( ...
    "Status", "PASS", ...
    "SmokeVersion", SmokeVersion, ...
    "SequenceIndex", SequenceIndex, ...
    "Flights", nFlight, ...
    "ControlRows", size(PC, 1), ...
    "ControlColumns", size(PC, 2), ...
    "TotalMainMissionFuel_kg", sum(Fuel_kg), ...
    "MaxConstraint", OptimizerOutput.MaxConstraint, ...
    "Feasible", logical(OptimizerOutput.Feasible), ...
    "ExitFlag", ExitFlag, ...
    "OptimizerIterations", OptimizerOutput.iterations, ...
    "OptimizerTime_min", OptimizerTime_min, ...
    "PHE_MTOW_kg", PHE.Specs.Weight.MTOW, ...
    "Conventional_MTOW_kg", Conventional.Specs.Weight.MTOW, ...
    "SizingMetadata", SizingMetadata, ...
    "Completed", string(datetime("now")));

save(fullfile(SmokeDir, "Sequence50_JointOpt_SmokeTest.mat"), ...
    "SmokeResult", "FlightSummary", "PC", "OptSeqTable", ...
    "OptimizerOutput", "SizingMetadata", "-v7.3");
writetable(FlightSummary, fullfile(SmokeDir, ...
    "Sequence50_JointOpt_SmokeTest_Flights.csv"));
writetable(struct2table(rmfield(SmokeResult, "SizingMetadata"), ...
    "AsArray", true), fullfile(SmokeDir, ...
    "Sequence50_JointOpt_SmokeTest_Summary.csv"));

fprintf(1, ['GREAT_LAKES_SMOKE_TEST=PASS\nSequence=%d Flights=%d ' ...
    'Fuel=%.9f kg MaxConstraint=%.12g\nResults=%s\n'], ...
    SequenceIndex, nFlight, sum(Fuel_kg), ...
    OptimizerOutput.MaxConstraint, SmokeDir);
WritePassMarker(MarkerFile, SmokeVersion);
end


function Value = RequireEnvironmentPath(Name)
Value = string(getenv(Name));
if strlength(Value) == 0
    error("GreatLakes:MissingEnvironment", ...
        "Required environment variable %s is not set.", Name);
end
Value = char(Value);
end


function WritePassMarker(MarkerFile, SmokeVersion)
Marker = fopen(MarkerFile, "w");
if Marker < 0
    error("GreatLakes:SmokeMarkerWrite", ...
        "Could not write smoke-test marker: %s", MarkerFile);
end
try
    Count = fprintf(Marker, "%s\n", SmokeVersion);
    CloseStatus = fclose(Marker);
catch ME
    fclose(Marker);
    rethrow(ME);
end
if Count < 1 || CloseStatus ~= 0
    error("GreatLakes:SmokeMarkerWrite", ...
        "Could not finish writing smoke-test marker: %s", MarkerFile);
end
end
