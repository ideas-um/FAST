function [BasePHE, BaseConventional, SizingMetadata] = ...
        SizeERJ175LRBatteryTechnology(BatterySpecificEnergy_Whkg, OutputFile)
%SIZEERJ175LRBATTERYTECHNOLOGY Resize the ERJ PHE at a specified battery technology.
%
% The HEA is resized from AircraftSpecsPkg.ERJ175LR_PHE after overriding
% gravimetric battery specific energy. The conventional aircraft is sized
% from the unchanged ERJ175LR definition for a controlled reference.

if nargin < 2, OutputFile = ""; end
validateattributes(BatterySpecificEnergy_Whkg, {'numeric'}, ...
    {'scalar','finite','positive'});

ConventionalDefinition = AircraftSpecsPkg.ERJ175LR();
PHEDefinition = AircraftSpecsPkg.ERJ175LR_PHE();
% Specification functions use kWh/kg before SpecProcessing converts to J/kg.
PHEDefinition.Specs.Power.SpecEnergy.Batt = ...
    BatterySpecificEnergy_Whkg / 1000;

BaseConventional = Main(ConventionalDefinition, ...
    @MissionProfilesPkg.ERJ_ClimbThenAccel);
BasePHE = Main(PHEDefinition, @MissionProfilesPkg.ERJ_ClimbThenAccel);

if ~logical(BaseConventional.Settings.Converged) || ...
        ~logical(BasePHE.Settings.Converged)
    error("FAST:BatteryTechnology:SizingDidNotConverge", ...
        "Conventional and %g Wh/kg PHE sizing must both converge.", ...
        BatterySpecificEnergy_Whkg);
end
if string(BasePHE.Specs.Propulsion.PropArch.Type) ~= "PHE" || ...
        string(BaseConventional.Specs.Propulsion.PropArch.Type) ~= "C"
    error("FAST:BatteryTechnology:WrongArchitecture", ...
        "Sized aircraft do not have the required PHE and conventional architectures.");
end

ActualSpecificEnergy_Whkg = ...
    BasePHE.Specs.Power.SpecEnergy.Batt / 3.6e3;
Tolerance = 1e-9 * max(1, BatterySpecificEnergy_Whkg);
if abs(ActualSpecificEnergy_Whkg - BatterySpecificEnergy_Whkg) > Tolerance
    error("FAST:BatteryTechnology:SpecificEnergyMismatch", ...
        "Requested %g Wh/kg but sized aircraft contains %g Wh/kg.", ...
        BatterySpecificEnergy_Whkg, ActualSpecificEnergy_Whkg);
end

SizingMetadata = struct( ...
    "Study", "resized HEA battery-specific-energy comparison", ...
    "BatterySpecificEnergy_Whkg", BatterySpecificEnergy_Whkg, ...
    "ActualBatterySpecificEnergy_Whkg", ActualSpecificEnergy_Whkg, ...
    "ConventionalSpecification", "AircraftSpecsPkg.ERJ175LR", ...
    "PHESpecification", "AircraftSpecsPkg.ERJ175LR_PHE with battery override", ...
    "MissionProfile", "MissionProfilesPkg.ERJ_ClimbThenAccel", ...
    "ConventionalConverged", logical(BaseConventional.Settings.Converged), ...
    "PHEConverged", logical(BasePHE.Settings.Converged), ...
    "PHE_MTOW_kg", BasePHE.Specs.Weight.MTOW, ...
    "PHE_OEW_kg", BasePHE.Specs.Weight.OEW, ...
    "PHE_BatteryWeight_kg", BasePHE.Specs.Weight.Batt, ...
    "PHE_BatteryEnergy_kWh", BasePHE.Specs.Weight.Batt * ...
        BasePHE.Specs.Power.SpecEnergy.Batt / 3.6e6, ...
    "PHE_DesignFuel_kg", BasePHE.Specs.Weight.Fuel, ...
    "PHE_ElectricMachineWeight_kg", BasePHE.Specs.Weight.EM, ...
    "Generated", string(datetime("now")));

if strlength(string(OutputFile)) > 0
    OutputFile = char(OutputFile);
    OutputDir = fileparts(OutputFile);
    if ~isempty(OutputDir) && ~isfolder(OutputDir), mkdir(OutputDir); end
    save(OutputFile, "BasePHE", "BaseConventional", ...
        "SizingMetadata", "-v7.3");
end
end
